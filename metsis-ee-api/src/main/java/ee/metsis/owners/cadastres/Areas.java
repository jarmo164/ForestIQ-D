package ee.metsis.owners.cadastres;

public class Areas {

    private Double area;
    private Double forestArea;
    private Double arableArea;
    private Double yardArea;
    private Double meadowArea;
    private Double underWaterArea;
    private Double buildingsArea;
    private Double otherArea;

    public Double getArea() {
        return area;
    }

    public void setArea(Double area) {
        this.area = area;
    }

    public Double getForestArea() {
        return forestArea;
    }

    public void setForestArea(Double forestArea) {
        this.forestArea = forestArea;
    }

    public Double getArableArea() {
        return arableArea;
    }

    public void setArableArea(Double arableArea) {
        this.arableArea = arableArea;
    }

    public Double getYardArea() {
        return yardArea;
    }

    public void setYardArea(Double yardArea) {
        this.yardArea = yardArea;
    }

    public Double getMeadowArea() {
        return meadowArea;
    }

    public void setMeadowArea(Double meadowArea) {
        this.meadowArea = meadowArea;
    }

    public Double getUnderWaterArea() {
        return underWaterArea;
    }

    public void setUnderWaterArea(Double underWaterArea) {
        this.underWaterArea = underWaterArea;
    }

    public Double getBuildingsArea() {
        return buildingsArea;
    }

    public void setBuildingsArea(Double buildingsArea) {
        this.buildingsArea = buildingsArea;
    }

    public Double getOtherArea() {
        return otherArea;
    }

    public void setOtherArea(Double otherArea) {
        this.otherArea = otherArea;
    }
}
